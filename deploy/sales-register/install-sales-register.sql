grant select on public.sales_register to authenticated;
grant all on public.sales_register to service_role;

alter table public.sales_register enable row level security;

drop policy if exists "Sales Register readable by screen access" on public.sales_register;
create policy "Sales Register readable by screen access" on public.sales_register
  for select to authenticated
  using ((select public.current_access_unrestricted()) or public.user_can_see(werks, prctr));

create index if not exists sales_register_fkdat_idx on public.sales_register (fkdat);
create index if not exists sales_register_werks_idx on public.sales_register (werks);
create index if not exists sales_register_prctr_idx on public.sales_register (prctr);

drop trigger if exists sales_register_updated_at on public.sales_register;
create trigger sales_register_updated_at before update on public.sales_register
  for each row execute function public.update_updated_at_column();

